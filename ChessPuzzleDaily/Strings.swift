func themeName(_ key: String, _ lang: Lang) -> String? {
    switch lang {
    case .ru: return THEME_NAMES[key]?.ru
    case .en: return THEME_NAMES[key]?.en
    case .uz: return THEME_NAMES[key]?.uz
    default:
        return THEME_NAMES_MORE[key]?[lang] ?? THEME_NAMES_ASIA[key]?[lang] ?? THEME_NAMES[key]?.en
    }
}
